#!/usr/bin/env node
/* Builds js/data/ssc-registry.js from SSC-text/<book>/chapters.json.
   node tools/gen-ssc-registry.js */
'use strict';
var fs=require('fs'), path=require('path');
var R=path.join(__dirname,'..'), B=path.join(R,'SSC-text');
var PAPERS=[
 ['sbn1','বাংলা ১ম পত্র','Bangla 1st Paper','bangla','Bangla 1st(1)','bn'],
 ['sbn2','বাংলা ২য় পত্র','Bangla 2nd Paper','bangla','Bangla 2nd','bn'],
 ['seng1','ইংরেজি ১ম পত্র','English 1st Paper','english','English 1st','en'],
 ['seng2','ইংরেজি ২য় পত্র','English 2nd Paper','english','Englist 2nd','en'],
 ['smath','সাধারণ গণিত','General Math','math','General Math','bn'],
 ['shm','উচ্চতর গণিত','Higher Math','hmath','Higher Math','bn'],
 ['sict','তথ্য ও যোগাযোগ প্রযুক্তি','ICT','ict','ICT','bn'],
 ['sphy','পদার্থবিজ্ঞান','Physics','phy','Physics','bn'],
 ['schem','রসায়ন','Chemistry','chem','Chemistry','bn'],
 ['sbio','জীববিজ্ঞান','Biology','bio','Biology','bn'],
 ['sbgs','বাংলাদেশ ও বিশ্বপরিচয়','BGS','bgs',null,'bn']
];
var out=["/* GENERATED by tools/gen-ssc-registry.js from each SSC-text book folder's chapters.json — do not edit by hand.",
"   The SSC edition (see js/edition.js). Internally the track is 'hsc' so every screen works unchanged. */",
"ICE.SSC = {sections:{}, topics:{}, subjects:[], path:[]};",
"(function(){ var S=ICE.SSC;",
"function SEC(id,name,en,subj,order,lang){ S.sections['hsc/'+id]={track:'hsc',id:id,name:name,en:en,subj:subj,n:25,spq:60,order:order,lang:lang,book:en}; }",
"function CH(sec,n,name,en,book,p0,p1){ var t='ssc.'+sec+'.ch'+n; S.topics[t]={id:t,sec:'hsc/'+sec,track:'hsc',n:n,name:name,w:1,note:en,book:book,ch:n,p0:p0,p1:p1}; S.path.push(t); }"];
var chapters={};
PAPERS.forEach(function(p,i){
  out.push("SEC("+JSON.stringify(p[0])+","+JSON.stringify(p[1])+","+JSON.stringify(p[2])+","+JSON.stringify(p[3])+","+(i+1)+","+JSON.stringify(p[5])+");");
  var list;
  if(p[4]) list=JSON.parse(fs.readFileSync(path.join(B,p[4],'chapters.json'),'utf8'));
  else list=[{n:1,bn:'বোর্ড ও টেস্ট প্রশ্ন',en:'Board & test questions',start:1,end:999}];
  chapters[p[0]]=list.length;
  list.forEach(function(c){
    out.push("CH("+JSON.stringify(p[0])+","+c.n+","+JSON.stringify(c.bn)+","+JSON.stringify(c.en)+","+JSON.stringify(c.book||p[4]||'')+","+c.start+","+c.end+");");
  });
});
out.push("S.subjects=[");
var subs=[['bangla','Bangla','বাংলা',['sbn1','sbn2']],['english','English','ইংরেজি',['seng1','seng2']],['math','Math','গণিত',['smath']],['hmath','Higher Math','উচ্চতর গণিত',['shm']],['ict','ICT','আইসিটি',['sict']],['phy','Physics','পদার্থবিজ্ঞান',['sphy']],['chem','Chemistry','রসায়ন',['schem']],['bio','Biology','জীববিজ্ঞান',['sbio']],['bgs','BGS','বাংলাদেশ ও বিশ্বপরিচয়',['sbgs']]];
out.push(subs.map(function(s){return "{id:"+JSON.stringify(s[0])+",en:"+JSON.stringify(s[1])+",bn:"+JSON.stringify(s[2])+",secs:"+JSON.stringify(s[3].map(function(x){return 'hsc/'+x;}))+"}";}).join(",\n"));
out.push("];\n})();");
fs.writeFileSync(path.join(R,'js/data/ssc-registry.js'),out.join("\n")+"\n");
console.log(JSON.stringify(chapters));
