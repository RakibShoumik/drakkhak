self.addEventListener('install', function(e){
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then(function(c){
    /* a data file that does not exist yet must not fail the install */
    return Promise.all(CORE.map(function(u){ return c.add(u).catch(function(){}); }));
  }));
});

self.addEventListener('activate', function(e){
  e.waitUntil(caches.keys().then(function(keys){
    return Promise.all(keys.map(function(k){ return k===CACHE ? null : caches.delete(k); }));
  }).then(function(){ return self.clients.claim(); }));
});

self.addEventListener('fetch', function(e){
  var req = e.request;
  if(req.method !== 'GET') return;

  var sameOrigin = new URL(req.url).origin === self.location.origin;

  /* the admin panel and the server's answers must always be live */
  if(sameOrigin && /\/(admin|api)\//.test(new URL(req.url).pathname)) return;

  if(!sameOrigin){
    e.respondWith(caches.match(req).then(function(hit){
      return hit || fetch(req).then(function(res){
        if(res && (res.status===200 || res.type==='opaque')){
          var copy=res.clone();
          caches.open(CACHE).then(function(c){ c.put(req, copy); });
        }
        return res;
      }).catch(function(){ return hit; });
    }));
    return;
  }

  e.respondWith(
    fetch(req).then(function(res){
      if(res && res.status===200 && res.type==='basic'){
        var copy=res.clone();
        caches.open(CACHE).then(function(c){ c.put(req, copy); });
      }
      return res;
    }).catch(function(){
      return caches.match(req, {ignoreSearch:true}).then(function(hit){
        return hit || caches.match('./index.html');
      });
    })
  );
});

/* let the page force an update without a reload dance */
self.addEventListener('message', function(e){
  if(e.data === 'skipWaiting') self.skipWaiting();
});
